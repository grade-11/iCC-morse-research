## This is a simple generator to build spheres for testing TDA tools/techniques. 

## Generate points forming the surface of a sphere in (up to) d-dimensions.  

## NAMING NOTE: the `dimension` parameter throughout this file is the AMBIENT embedding dimension, not the
## standard topological sphere index n.  By the standard convention, S^n (the n-sphere) is embedded in R^(n+1)
## -- so a circle is S^1 (embedded in R^2), an ordinary sphere is S^2 (embedded in R^3), and in general
## dimension=d here produces S^(d-1).  This file intentionally keeps `dimension` as ambient dimension (rather
## than renaming it to the standard n-sphere index) so existing calls elsewhere in the codebase keep working;
## every docstring and generated filename below states the resulting S^n index explicitly to avoid ambiguity.

## generate a point cloud representation for a d-sphere using Muller's method [Muller-59].  this method generates uniform random
## points on a boundary of a d-sphere.  the boundary of points follows a uniform random distribution between radii r1 < r2.

## [Muller-59] Mervin E. Muller, "A note on a method for generating points uniformly on n-dimensional
##             spheres." Communications of the  ACM, 19-20, vol2, no 4, April
##             1959. DOI=http://dx.doi.org/10.1145/377939.377946 

